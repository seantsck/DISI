#!/usr/bin/env node
// Generates analytics-effects.md: what Migration 034 changes and does not change, computed on a fresh 001-034 replay and the
// 033 baseline stored in audit-report.json.
//
//   node database/research/034/effects.mjs

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildCanonicalChain } from '../../../tests/db/canonical-chain.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const audit = JSON.parse(fs.readFileSync(path.join(here, 'audit-report.json'), 'utf8'))
const chain = await buildCanonicalChain()
const q = (s, p) => chain.query(s, p)
const n2 = (v) => (v === null || v === undefined ? 'unknown' : Number(v).toFixed(2))

const lines = []
const out = (s = '') => lines.push(s)
const table = (head, rows) => {
  out(`| ${head.join(' | ')} |`)
  out(`|${head.map(() => '---').join('|')}|`)
  for (const r of rows) out(`| ${r.join(' | ')} |`)
  out()
}

const base = audit.baseline_033.portfolio_all
const now = (await q(`select * from v_dodgers_international_value_portfolio where grain = 'ALL'`))[0]
out('# Analytics effects of Migration 034')
out()
out('Generated by `node database/research/034/effects.mjs` on a fresh 001-034 replay. 033 values come from `audit-report.json`.')
out()
out('## Portfolio (all tracked signings)')
out()
table(['Measure', '033', '034', 'Note'], [
  ['Direct bWAR per $1M (COMPLETE cost, mature)', base.aggregate_direct_dodgers_bwar_per_million, now.aggregate_direct_dodgers_bwar_per_million, 'unchanged'],
  ['Attributable bWAR per $1M (033 definition)', base.aggregate_attributable_organizational_bwar_per_million, now.aggregate_attributable_organizational_bwar_per_million, 'legacy columns preserved'],
  ['Ratio-eligible signings', base.attributable_ratio_eligible_signings, now.attributable_ratio_eligible_signings, 'unchanged'],
  ['Attributable first-hop trade return (033)', n2(base.attributable_trade_return_bwar), n2(now.attributable_trade_return_bwar), 'legacy column, unchanged'],
  ['Package return summed per signing (033 column)', n2(base.package_return_dodgers_bwar), n2(now.package_return_dodgers_bwar), 'legacy column, unchanged; repeats a package with several tracked signings'],
  ['Interval-bounded first-hop PLAYER_ATTRIBUTABLE return', 'n/a', n2(now.interval_bounded_individually_attributable_first_hop_bwar), 'adds Fernandez (Valo timing resolved) and Axel Perez'],
  ['Interval-bounded first-hop package bWAR (per package, once)', 'n/a', n2(now.interval_bounded_first_hop_package_bwar), `${now.root_packages} root packages; Blake and Hundley re-entry removed, Edman / Valo / McDermott resolved`],
  ['Downstream individually attributable bWAR', 'n/a', n2(now.downstream_individually_attributable_bwar), 'PLAYER_ATTRIBUTABLE at hop 2 or later'],
  ['Downstream package-attributable bWAR', 'n/a', n2(now.downstream_package_attributable_bwar), 'PACKAGE_ATTRIBUTABLE at hop 2 or later; belongs to a package, not a signing'],
  ['Observable-not-attributable bWAR (each interval once)', 'n/a', n2(now.observable_not_attributable_bwar), 'mixed-lineage value; visible, added to no root'],
  ['Package-deduplicated total (every interval once)', 'n/a', n2(now.package_deduplicated_total_bwar), 'all attribution levels, no double count'],
  ['Total individually attributable bWAR per $1M', 'n/a', now.aggregate_total_individually_attributable_bwar_per_million, `${now.total_attributable_ratio_eligible_signings} eligible signings`],
  ['Packages with downstream realization', 'n/a', now.packages_with_downstream_realization, ''],
  ['Packages blocked by mixed lineage', 'n/a', now.packages_blocked_by_mixed_lineage, ''],
  ['Packages incomplete / open', 'n/a', `${now.packages_incomplete} / ${now.packages_open}`, ''],
  ['Maximum observed depth', 'n/a', now.max_observed_depth, ''],
])

out('## First-hop interval corrections (033 column preserved beside the bounded value)')
out()
const corr = await q(`select r.player_slug, r.trade_package_return_dodgers_bwar::text as legacy, d.interval_bounded_first_hop_package_bwar::text as bounded
  from v_player_organizational_realization r join v_downstream_organizational_realization d on d.player_id = r.player_id and d.row_grain = 'SIGNING'
  where r.trade_package_return_dodgers_bwar is distinct from d.interval_bounded_first_hop_package_bwar order by 1`)
table(['Signing', '033 package return', '034 interval-bounded'], corr.map((r) => [r.player_slug, n2(r.legacy), n2(r.bounded)]))

out('## Control intervals that are not the first interval of a return asset')
out()
const ints = await q(`select display_name, start_method, interval_start::text as s, coalesce(interval_end::text, 'open') as e, interval_status, interval_bounded_dodgers_bwar::text as w
  from v_player_control_intervals where start_method <> 'TRACKED_SIGNING' and exists (select 1 from v_player_control_intervals b where b.display_name = v_player_control_intervals.display_name and b.interval_key <> v_player_control_intervals.interval_key and b.start_method <> 'TRACKED_SIGNING')
  order by 1, 3`)
table(['Player', 'Start', 'From', 'To', 'Status', 'Interval bWAR'], ints.map((r) => [r.display_name, r.start_method, r.s, r.e, r.interval_status, n2(r.w)]))

out('## Lineage by hop and attribution level (root package x path rows)')
out()
const lin = await q(`select hop_number, attribution_level, count(*)::int as n from v_transaction_asset_lineage group by 1, 2 order by 1, 2`)
table(['Hop', 'Attribution level', 'Rows'], lin.map((r) => [r.hop_number, r.attribution_level, r.n]))
const dist = await q(`select hop_number, count(distinct interval_key)::int as n from v_transaction_asset_lineage group by 1 order by 1`)
out(`Distinct control intervals per hop: ${dist.map((r) => `hop ${r.hop_number} = ${r.n}`).join(', ')}.`)
out()

out('## Chain status of the tracked signings with a trade')
out()
const st = await q(`select chain_status, count(*)::int as n from v_downstream_organizational_realization where row_grain = 'SIGNING' group by 1 order by 1`)
table(['Chain status', 'Signings'], st.map((r) => [r.chain_status, r.n]))
out(`The 033 \`downstream_asset_chain_incomplete\` flag is preserved (${audit.baseline.downstream_flag} signings); most of those are complete terminal chains.`)
out()

out('## Research queues')
out()
const rq = await q(`select issue, count(*)::int as n from v_value_research_queue group by 1 union all select issue, count(*)::int from v_transaction_research_queue group by 1 order by 1`)
table(['Issue', 'Rows'], rq.map((r) => [r.issue, r.n]))

fs.writeFileSync(path.join(here, 'analytics-effects.md'), lines.join('\n') + '\n')
await chain.close()
console.log('wrote analytics-effects.md')
